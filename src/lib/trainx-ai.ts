// Система для messages.create: мастер-промт + специализированный модуль роута.
// cache_control на обоих блоках — общий префикс (мастер) шарится между всеми
// фичами, полный префикс (мастер+модуль) кэшируется на каждую фичу.
export function trainxSystem(moduleText: string) {
  return [
    {
      type: 'text' as const,
      text: TRAINX_MASTER_PROMPT,
      cache_control: { type: 'ephemeral' as const },
    },
    {
      type: 'text' as const,
      text: 'СПЕЦИАЛИЗИРОВАННЫЙ МОДУЛЬ ЭТОГО ЗАПРОСА:\n' + moduleText,
      cache_control: { type: 'ephemeral' as const },
    },
  ];
}
