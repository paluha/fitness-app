const DEFAULT_NAMES = new Map(
  DEFAULT_WORKOUTS.flatMap(w => w.exercises.map(e => [`${w.id}/${e.id}`, e.name] as const)),
);

type NamedExercise = { id?: unknown; name?: unknown };

/**
 * Название в записи дня — след ошибки, а не то, что делали: пустое или
 * в точности из встроенного шаблона на том же месте.
 */
export function isSuspectName(workoutId: string | null | undefined, e: NamedExercise): boolean {
  const name = typeof e.name === 'string' ? e.name.trim() : '';
  if (!name) return true;
  return !!workoutId && DEFAULT_NAMES.get(`${workoutId}/${String(e.id)}`) === name;
}

/**
 * Подозрительные названия заменяем названиями из программы, что
 * действовала в тот день (nameOf по номеру упражнения). Остальные не
 * трогаем: правка тренировки через ИИ может переиспользовать номер, и
 * сохранённое название — единственная память о том, что делали.
 * Возвращает null, если менять нечего.
 */
export function repairExerciseNames<T extends NamedExercise>(
  workoutId: string | null | undefined,
  exercises: T[],
  nameOf: (exerciseId: string) => string | undefined,
): T[] | null {
  let changed = false;
  const out = exercises.map(e => {
    if (!e || !isSuspectName(workoutId, e)) return e;
    const name = nameOf(String(e.id));
    if (!name || name === e.name) return e;
    changed = true;
    return { ...e, name };
  });
  return changed ? out : null;
}
